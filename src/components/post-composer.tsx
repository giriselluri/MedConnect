'use client';

import React, { useState, useEffect } from 'react';
import { useApp } from '@/lib/context';
import { Post } from '@/types';
import {
  Send,
  Link as LinkIcon,
  Tag,
  Stethoscope,
  X,
  FileCheck,
  Globe,
  Loader2,
  Users,
  UserCheck,
  Compass,
  ChevronDown,
} from 'lucide-react';
import { SpecialtyBadge } from './specialty-badge';
import { trackAppEvent } from '@/lib/analytics';

interface PostComposerProps {
  onPostCreated: (post: Post) => void;
  groupId?: string;
  defaultSpecialtyId?: string;
  placeholder?: string;
}

export function PostComposer({
  onPostCreated,
  groupId,
  defaultSpecialtyId,
  placeholder,
}: PostComposerProps) {
  const { currentUser, specialties, isDemoUser } = useApp();
  const [content, setContent] = useState('');
  const [specialtyId, setSpecialtyId] = useState(defaultSpecialtyId || '');
  const [tagsInput, setTagsInput] = useState('');
  const [tags, setTags] = useState<string[]>([]);
  const [showAttachUrl, setShowAttachUrl] = useState(false);
  const [articleUrl, setArticleUrl] = useState('');
  const [articleTitle, setArticleTitle] = useState('');
  const [articleSource, setArticleSource] = useState('');
  const [visibility, setVisibility] = useState<'everyone' | 'connections' | 'followers' | 'group'>(
    groupId ? 'group' : 'everyone'
  );
  const [selectedGroupId, setSelectedGroupId] = useState<string>(groupId || '');
  const [groups, setGroups] = useState<Array<{ id: string; name: string }>>([]);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    fetch('/api/groups')
      .then((r) => (r.ok ? r.json() : null))
      .then((data) => {
        if (data?.groups) {
          setGroups(data.groups);
          if (!selectedGroupId && data.groups.length > 0) {
            setSelectedGroupId(data.groups[0].id);
          }
        }
      })
      .catch(() => {});
  }, [selectedGroupId]);

  // Load pending draft generated by AI Research Assistant
  useEffect(() => {
    if (typeof window === 'undefined') return;
    const pendingJson = sessionStorage.getItem('medconnect_pending_post');
    const legacyDraft = sessionStorage.getItem('medconnect_post_draft');

    if (pendingJson) {
      try {
        const parsed = JSON.parse(pendingJson);
        if (parsed.content) setContent(parsed.content);
        if (parsed.article_title) {
          setArticleTitle(parsed.article_title);
          setShowAttachUrl(true);
        }
        if (parsed.article_url) {
          setArticleUrl(parsed.article_url);
          setShowAttachUrl(true);
        }
        if (parsed.tags && Array.isArray(parsed.tags)) {
          setTags(parsed.tags);
        }
      } catch {
        setContent(pendingJson);
      }
      sessionStorage.removeItem('medconnect_pending_post');
    } else if (legacyDraft) {
      setContent(legacyDraft);
      sessionStorage.removeItem('medconnect_post_draft');
    }
  }, []);

  const handleAddTag = () => {
    const cleaned = tagsInput.replace(/[^a-zA-Z0-9]/g, '').trim();
    if (cleaned && !tags.includes(cleaned)) {
      setTags([...tags, cleaned]);
      setTagsInput('');
    }
  };

  const handleRemoveTag = (tagToRemove: string) => {
    setTags(tags.filter((t) => t !== tagToRemove));
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!content.trim()) return;

    setIsSubmitting(true);
    setError(null);

    try {
      const res = await fetch('/api/posts', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          content: content.trim(),
          specialty_id: specialtyId || undefined,
          topic_tags: tags,
          article_url: articleUrl.trim() || undefined,
          article_title: articleTitle.trim() || undefined,
          article_source: articleSource.trim() || undefined,
          group_id: visibility === 'group' ? (selectedGroupId || groupId || undefined) : undefined,
          visibility,
        }),
      });

      if (!res.ok) {
        const data = await res.json();
        throw new Error(data.error || 'Failed to create post');
      }

      const { post } = await res.json();
      onPostCreated(post);

      // Track post created event (only fired on success, excluding demo users)
      trackAppEvent(
        'post_created',
        {
          specialty: post.specialty_id || 'general',
          visibility: post.visibility || 'everyone',
          has_tags: Boolean(post.topic_tags && post.topic_tags.length > 0),
          has_article: Boolean(post.article_url),
        },
        isDemoUser
      );

      // Reset composer
      setContent('');
      setSpecialtyId(defaultSpecialtyId || '');
      setTags([]);
      setTagsInput('');
      setArticleUrl('');
      setArticleTitle('');
      setArticleSource('');
      setShowAttachUrl(false);
    } catch (err: any) {
      setError(err.message || 'An error occurred while publishing your post');
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <div className="bg-white rounded-xl shadow-xs border border-slate-200 p-4">
      {/* Top row: Avatar + Textarea */}
      <div className="flex gap-3">
        <img
          src={currentUser?.avatar_url || 'https://images.unsplash.com/photo-1551601651-2a8555f1a136?auto=format&fit=crop&q=80&w=100'}
          alt={currentUser?.full_name || 'User'}
          onError={(e) => {
            e.currentTarget.src = `https://ui-avatars.com/api/?name=${encodeURIComponent(currentUser?.full_name || 'User')}&background=0d9488&color=fff&bold=true`;
          }}
          className="w-10 h-10 rounded-full object-cover border border-slate-200 flex-shrink-0"
        />
        <div className="flex-1 min-w-0">
          <textarea
            value={content}
            onChange={(e) => setContent(e.target.value)}
            placeholder={
              placeholder ||
              `Share a clinical insight, trial finding, or case question, Dr. ${
                currentUser?.full_name?.split(' ')[1] || 'Colleague'
              }...`
            }
            rows={3}
            className="w-full text-xs sm:text-sm text-slate-800 placeholder:text-slate-400 border border-slate-200 rounded-xl p-3 focus:outline-none focus:border-teal-500 focus:ring-1 focus:ring-teal-500 transition resize-none bg-slate-50/50 hover:bg-white"
          />
        </div>
      </div>

      {/* URL Attachment Panel */}
      {showAttachUrl && (
        <div className="mt-3 p-3 bg-slate-50 rounded-xl border border-slate-200 space-y-2 text-xs">
          <div className="flex items-center justify-between">
            <span className="font-semibold text-slate-700 flex items-center gap-1.5">
              <LinkIcon className="w-3.5 h-3.5 text-teal-600" />
              Attach Scientific Reference or Article URL
            </span>
            <button
              onClick={() => setShowAttachUrl(false)}
              className="text-slate-400 hover:text-slate-600"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
            <input
              type="url"
              value={articleUrl}
              onChange={(e) => setArticleUrl(e.target.value)}
              placeholder="https://nejm.org/doi/... or journal link"
              className="px-2.5 py-1.5 border border-slate-200 rounded-lg bg-white text-xs text-slate-800 focus:outline-none focus:border-teal-500"
            />
            <input
              type="text"
              value={articleTitle}
              onChange={(e) => setArticleTitle(e.target.value)}
              placeholder="Article or Trial Title"
              className="px-2.5 py-1.5 border border-slate-200 rounded-lg bg-white text-xs text-slate-800 focus:outline-none focus:border-teal-500"
            />
          </div>
          <input
            type="text"
            value={articleSource}
            onChange={(e) => setArticleSource(e.target.value)}
            placeholder="Journal or Source (e.g., NEJM, The Lancet, JAMA)"
            className="w-full px-2.5 py-1.5 border border-slate-200 rounded-lg bg-white text-xs text-slate-800 focus:outline-none focus:border-teal-500"
          />
        </div>
      )}

      {/* Tags row */}
      {tags.length > 0 && (
        <div className="mt-2 flex flex-wrap gap-1.5">
          {tags.map((tag) => (
            <span
              key={tag}
              className="inline-flex items-center gap-1 text-[11px] font-semibold bg-slate-100 text-slate-700 px-2 py-0.5 rounded-md border border-slate-200"
            >
              #{tag}
              <button onClick={() => handleRemoveTag(tag)} className="text-slate-400 hover:text-slate-600">
                <X className="w-3 h-3" />
              </button>
            </span>
          ))}
        </div>
      )}

      {error && (
        <div className="mt-2 text-xs text-red-600 font-medium bg-red-50 p-2 rounded-lg border border-red-200">
          {error}
        </div>
      )}

      {/* Bottom controls row */}
      <div className="mt-3 pt-3 border-t border-slate-100 flex flex-wrap items-center justify-between gap-2.5">
        <div className="flex flex-wrap items-center gap-1.5 sm:gap-2">
          {/* Audience / Share-with Dropdown */}
          <div className="relative inline-flex items-center">
            <select
              value={visibility}
              onChange={(e) => setVisibility(e.target.value as any)}
              className="text-xs bg-slate-100 hover:bg-slate-200/80 border border-slate-200 text-slate-800 font-medium rounded-lg px-2.5 py-1.5 pr-6 appearance-none focus:outline-none cursor-pointer transition"
              title="Select who can see this post"
            >
              <option value="everyone">🌐 Everyone</option>
              <option value="connections">👥 Connections</option>
              <option value="followers">👤 Followers</option>
              <option value="group">🏢 Group</option>
            </select>
            <ChevronDown className="w-3.5 h-3.5 text-slate-500 absolute right-2 pointer-events-none" />
          </div>

          {/* Group Picker if visibility is group and no fixed groupId was provided */}
          {visibility === 'group' && !groupId && groups.length > 0 && (
            <div className="relative inline-flex items-center">
              <select
                value={selectedGroupId}
                onChange={(e) => setSelectedGroupId(e.target.value)}
                className="text-xs bg-teal-50 border border-teal-200 text-teal-900 font-medium rounded-lg px-2.5 py-1.5 pr-6 appearance-none focus:outline-none cursor-pointer"
              >
                {groups.map((g) => (
                  <option key={g.id} value={g.id}>
                    {g.name}
                  </option>
                ))}
              </select>
              <ChevronDown className="w-3.5 h-3.5 text-teal-700 absolute right-2 pointer-events-none" />
            </div>
          )}

          {/* Specialty Picker */}
          <div className="relative inline-flex items-center">
            <select
              value={specialtyId}
              onChange={(e) => setSpecialtyId(e.target.value)}
              className="text-xs bg-teal-50/70 border border-teal-200 text-teal-900 font-medium rounded-lg px-2.5 py-1.5 pr-6 appearance-none focus:outline-none hover:bg-teal-100 cursor-pointer"
            >
              <option value="">Select Specialty</option>
              {specialties.map((s) => (
                <option key={s.id} value={s.id}>
                  {s.name}
                </option>
              ))}
            </select>
            <Stethoscope className="w-3.5 h-3.5 text-teal-700 absolute right-2 pointer-events-none" />
          </div>

          {/* Toggle URL Attachment */}
          <button
            type="button"
            onClick={() => setShowAttachUrl(!showAttachUrl)}
            className={`inline-flex items-center gap-1 text-xs px-2.5 py-1.5 rounded-lg border transition ${
              showAttachUrl || articleUrl
                ? 'bg-teal-50 text-teal-800 border-teal-300'
                : 'text-slate-600 hover:bg-slate-50 border-slate-200'
            }`}
          >
            <LinkIcon className="w-3.5 h-3.5 text-teal-600" />
            <span className="hidden sm:inline">Reference Link</span>
          </button>

          {/* Topic tag input */}
          <div className="inline-flex items-center gap-1 bg-slate-50 border border-slate-200 rounded-lg px-2 py-1 text-xs">
            <Tag className="w-3.5 h-3.5 text-slate-400" />
            <input
              type="text"
              value={tagsInput}
              onChange={(e) => setTagsInput(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter') {
                  e.preventDefault();
                  handleAddTag();
                }
              }}
              placeholder="Add #tag..."
              className="w-20 bg-transparent text-xs text-slate-800 focus:outline-none placeholder:text-slate-400"
            />
            {tagsInput && (
              <button
                type="button"
                onClick={handleAddTag}
                className="text-[10px] font-bold text-teal-700 hover:underline"
              >
                +
              </button>
            )}
          </div>
        </div>

        {/* Submit Button */}
        <button
          onClick={handleSubmit}
          disabled={!content.trim() || isSubmitting}
          className="inline-flex items-center gap-1.5 px-4 py-1.5 bg-teal-700 hover:bg-teal-800 disabled:opacity-50 disabled:cursor-not-allowed text-white text-xs font-semibold rounded-lg shadow-xs transition"
        >
          {isSubmitting ? (
            <>
              <Loader2 className="w-3.5 h-3.5 animate-spin" />
              <span>Publishing...</span>
            </>
          ) : (
            <>
              <Send className="w-3.5 h-3.5" />
              <span>Share Insight</span>
            </>
          )}
        </button>
      </div>
    </div>
  );
}
